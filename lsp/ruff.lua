-- =============================================================================
-- lsp/ruff.lua — конфигурация Ruff LSP для Python
-- =============================================================================
-- Ruff — Python-линтер и источник быстрых исправлений, написанный на Rust.
-- Форматирование выполняет Conform через `ruff format`; этот сервер отвечает за LSP-диагностику.
-- Конфигурация Ruff ищется в `pyproject.toml`, `ruff.toml` или `.ruff.toml` проекта.
-- =============================================================================

return {
	cmd = { "ruff", "server" }, -- запуск Ruff в режиме LSP-сервера

	filetypes = { "python" }, -- активировать только для .py файлов

	-- Маркеры корня проекта: LSP будет искать эти файлы вверх по дереву.
	root_markers = { "pyproject.toml", "ruff.toml", ".ruff.toml" },

	-- Ruff использует UTF-16 для позиций LSP; без этого возможны смещения диагностики.
	capabilities = { offsetEncoding = { "utf-16" } },
}
