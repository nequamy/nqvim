-- =============================================================================
-- lsp/ruff.lua — конфигурация Ruff LSP для Python
-- =============================================================================
-- Ruff — молниеносный Python линтер и форматтер написанный на Rust.
-- Заменяет: flake8, pylint, isort, black и десятки других инструментов.
-- В сотни раз быстрее аналогов благодаря Rust.
--
-- Установка: pip install ruff  или  :MasonInstall ruff
-- Конфигурация Ruff: pyproject.toml / ruff.toml / .ruff.toml в корне проекта
-- =============================================================================

return {
	cmd = { "ruff", "server" }, -- режим LSP сервера

	filetype = { "python" }, -- активировать только для .py файлов

	-- Маркеры корня проекта: LSP будет искать эти файлы вверх по дереву.
	root_markers = { "pyproject.toml", "ruff.toml", ".ruff.toml" },

	-- Исправление несоответствия кодировок позиций между Neovim и Ruff.
	-- Neovim по умолчанию использует utf-8, но многие LSP серверы (включая Ruff)
	-- работают с utf-16 позициями (стандарт LSP протокола).
	-- Без этого могут быть смещения диагностики и неправильные позиции курсора.
	capabilities = { offsetEncoding = { "utf-16" } }
}
