-- =============================================================================
-- lsp/ty.lua — конфигурация Ty type checker для Python
-- =============================================================================
-- Ty — новый Python type checker от команды Astral (авторы Ruff и uv).
-- Альтернатива pyright и mypy. Написан на Rust, работает значительно быстрее.
--
-- Внимание: по состоянию на 2025 Ty находится в активной разработке (beta).
-- Для стабильных проектов можно использовать pyright вместо ty.
--
-- Установка: pip install ty  или  через Mason когда появится поддержка
-- =============================================================================

return {
	cmd = { "ty", "server" }, -- команда запуска LSP режима

	filetypes = { "python" }, -- активировать только для .py файлов

	-- Определение корня проекта через vim.fs.root.
	-- 0 — буфер для которого запускается LSP.
	-- Ищет вверх по директориям пока не найдёт .git/ или pyproject.toml.
	root_dir = vim.fs.root(0, { ".git/", "pyproject.toml" }),
}
