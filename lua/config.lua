-- =============================================================================
-- config.lua — базовые настройки редактора
-- =============================================================================
-- Здесь только vim.opt настройки — без плагинов, без биндингов.
-- Всё что касается внешнего вида, поведения редактора и удобства набора текста.
-- =============================================================================

-- Нумерация строк: абсолютный номер текущей строки + относительные для остальных.
vim.opt.nu = true
vim.opt.relativenumber = true

-- Настройки отступов (табуляция = 4 пробела).
-- tabstop     — ширина символа Tab при отображении
-- softtabstop — ширина Tab при нажатии клавиши (в режиме вставки)
-- shiftwidth  — ширина отступа при >> / << / автоиндент
vim.opt.tabstop = 4
vim.opt.softtabstop = 4
vim.opt.shiftwidth = 4

-- Скруглённые рамки для всплывающих окон (hover, диагностика, автодополнение).
vim.opt.winborder = "rounded"

-- Синхронизация буфера обмена с системным.
vim.opt.clipboard = "unnamedplus"

-- Всегда показывать колонку знаков (иконки LSP диагностики, gitsigns и т.д.).
vim.opt.signcolumn = "yes"

-- Сколько строк оставлять видимыми выше/ниже курсора при скролле.
vim.opt.scrolloff = 8

-- Сохранение истории отмен между сессиями.
vim.opt.undofile = true

-- Отключаем перенос строк — длинные строки уходят за экран.
vim.opt.wrap = true

-- Новые вертикальные сплиты открываются справа (а не слева).
vim.opt.splitright = true
-- Новые горизонтальные сплиты открываются снизу (а не сверху).
vim.opt.splitbelow = true

-- Подавляем лишние сообщения в командной строке.
-- s — "search hit BOTTOM, continuing at TOP" и аналогичные
-- I — стартовое сообщение Neovim (логотип при старте без файла, если нет dashboard)
-- c — "ins-completion-menu" сообщения
-- C — сканирование тегов
-- W — "written" при сохранении
-- F — "file info" при открытии файла
vim.opt.shortmess:append("sIcCWF")

-- Клавиша-лидер: Space. Используется как префикс для большинства биндингов.
vim.g.mapleader = " "

-- Умный регистр при поиске:
-- ignorecase — поиск без учёта регистра по умолчанию
-- smartcase  — если в паттерне есть заглавные буквы, регистр учитывается
vim.opt.ignorecase = true
vim.opt.smartcase = true

-- Умный автоиндент: Neovim сам определяет уровень отступа при нажатии Enter.
vim.opt.smartindent = true

-- Подсвечивать строку с курсором. Помогает быстро найти где ты находишься.
vim.opt.cursorline = true

-- Включить поддержку 24-битных цветов (RGB).
-- Необходимо для корректного отображения большинства цветовых схем.
-- Требует терминал с поддержкой true color (iTerm2, Alacritty, Kitty и др.).
vim.opt.termguicolors = true

-- Задержка перед записью swap-файла и срабатыванием CursorHold событий (в мс).
-- 250 мс — баланс между отзывчивостью и нагрузкой. Влияет на скорость
-- появления gitsigns, LSP диагностики, и других плагинов использующих CursorHold.
vim.opt.updatetime = 250

-- Время ожидания между нажатиями клавиш в составных командах (мс).
vim.opt.timeoutlen = 400
